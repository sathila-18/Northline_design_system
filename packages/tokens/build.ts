// Token build (S2). Reads tokens/design.tokens.json with Style Dictionary and writes to dist/:
//   tokens.css           CSS variables: primitives and spacing/radius on :root, aliases per brand on [data-brand],
//                        semantic tokens per theme on [data-theme] (DESIGN.md §3.8)
//   tokens.js, .d.ts     semantic token names and the full chain (for Storybook's Token pipeline page)
//   tailwind-theme.css   the Tailwind 4 theme: semantic colours, text styles, spacing, radius, sizes, shadows, z-index
// Run: node build.ts (Node 24 runs TypeScript directly). Never edit dist/ by hand.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import type { DesignTokens, TransformedToken } from 'style-dictionary/types';
import { BRANDS, THEMES, cssName, tailwindKeys, textStyleName, type Brand, type Theme } from './src/naming.ts';

const SOURCE = fileURLToPath(new URL('../../tokens/design.tokens.json', import.meta.url));
const DIST = fileURLToPath(new URL('dist/', import.meta.url));
const ALPHA_EXTENSION = 'com.northline.alpha';
const FONT_FALLBACK = 'system-ui, sans-serif'; // DESIGN.md §3.4
const HEADER = '/* Generated by packages/tokens/build.ts from tokens/design.tokens.json. Do not edit. */\n';
const REFERENCE = /^\{([^{}]+)\}$/;

// Shadows and z-index are hand-written in src/styles.css (S3, DESIGN.md §4.1 and §4.3); the theme points at them.
const SHADOWS = ['resting', 'panel', 'menu', 'sticky', 'sticky-end'];
const LAYERS = ['base', 'sticky', 'overlay', 'modal', 'menu', 'tooltip', 'snackbar'];
const TABULAR_STYLES = new Set(['data-l', 'data-m']); // DESIGN.md §3.4

type Json = Record<string, unknown>;
type ModeMap = Record<string, unknown>;

StyleDictionary.registerTransform({
  name: 'name/nl',
  type: 'name',
  transform: (token) => cssName(token.path),
});

/** A copy of the token tree with every $value replaced by its value in the given brand and theme. */
function pickModes(node: unknown, brand: Brand, theme: Theme): unknown {
  if (Array.isArray(node) || typeof node !== 'object' || node === null) return node;
  const object = node as Json;
  if ('$value' in object) {
    const modes = ((object.$extensions as Json | undefined)?.mode ?? {}) as ModeMap;
    const value = brand in modes ? modes[brand] : theme in modes ? modes[theme] : object.$value;
    return { ...object, $value: value };
  }
  return Object.fromEntries(Object.entries(object).map(([key, child]) => [key, pickModes(child, brand, theme)]));
}

async function tokensFor(source: Json, brand: Brand, theme: Theme): Promise<TransformedToken[]> {
  const sd = new StyleDictionary({
    tokens: pickModes(source, brand, theme) as DesignTokens,
    platforms: { css: { transforms: ['name/nl'] } },
    log: { verbosity: 'silent' },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  return allTokens;
}

const collection = (token: TransformedToken) => token.path[0];

/** The opacity an Alpha token has in a theme (com.northline.alpha), or undefined. */
const alphaOf = (token: TransformedToken, theme: Theme) =>
  (
    (token.$extensions as Record<string, unknown> | undefined)?.[ALPHA_EXTENSION] as Record<Theme, number> | undefined
  )?.[theme];

/** The CSS value of a token: a var() for a reference, otherwise the raw value in CSS form. */
function cssValue(token: TransformedToken, names: Map<string, string>, theme: Theme): string {
  const original: unknown = token.original.$value;
  const match = typeof original === 'string' ? REFERENCE.exec(original) : null;
  let value: string;
  if (match?.[1]) {
    const target = names.get(match[1]);
    if (!target) throw new Error(`${token.path.join('.')} points at a missing token: ${match[1]}`);
    value = `var(--${target})`;
  } else if (token.$type === 'dimension') {
    const { value: amount, unit } = original as { value: number; unit: string };
    value = `${amount}${unit}`;
  } else if (token.$type === 'fontFamily') {
    value = `"${String(original)}", ${FONT_FALLBACK}`;
  } else {
    value = String(original);
  }
  const alpha = alphaOf(token, theme);
  if (alpha !== undefined) value = `color-mix(in srgb, ${value} ${+(alpha * 100).toFixed(2)}%, transparent)`;
  return value;
}

function block(selector: string, lines: string[]): string {
  return `${selector} {\n${lines.map((line) => `  ${line}`).join('\n')}\n}\n`;
}

const source = JSON.parse(await readFile(SOURCE, 'utf8')) as Json;
const reference = await tokensFor(source, 'Northline', 'Light');
const names = new Map(reference.map((token) => [token.path.join('.'), token.name]));
// A text style is an Alias Typography group with a font size. Other groups (Icon: only a weight) are plain aliases
// and get no font shorthand or text utility.
const textStyleGroups = new Set(
  reference.filter((t) => collection(t) === 'Alias Typography' && t.path[2] === 'Font size').map((t) => t.path[1]),
);
const isTextStyleToken = (t: TransformedToken) =>
  collection(t) === 'Alias Typography' && textStyleGroups.has(t.path[1]);
const declarations = (tokens: TransformedToken[], theme: Theme) =>
  tokens.map((token) => `--${token.name}: ${cssValue(token, names, theme)};`);

const css: string[] = [HEADER];

// Primitives and spacing/radius have no modes.
css.push(
  block(
    ':root',
    declarations(
      reference.filter((t) => ['Primitives', 'Alias Spacing & Radius'].includes(collection(t) ?? '')),
      'Light',
    ),
  ),
);

// Aliases per brand. Northline is also the default on :root. Each text style also gets a font shorthand.
const brandChains: Record<string, Record<Brand, string>> = {};
for (const brand of BRANDS) {
  const tokens = (await tokensFor(source, brand, 'Light')).filter((t) =>
    ['Alias Colors', 'Alias Typography'].includes(collection(t) ?? ''),
  );
  const lines = declarations(tokens, 'Light');
  const styles = [...new Set(tokens.filter(isTextStyleToken).map((t) => t.path[1] ?? ''))];
  for (const style of styles) {
    const n = `nl-font-${textStyleName(style)}`;
    lines.push(`--${n}: var(--${n}-weight) var(--${n}-size)/var(--${n}-line-height) var(--${n}-family);`);
  }
  for (const token of tokens) {
    const match = REFERENCE.exec(String(token.original.$value));
    (brandChains[`--${token.name}`] ??= {} as Record<Brand, string>)[brand] = `--${names.get(match?.[1] ?? '') ?? ''}`;
  }
  const selector = brand === 'Northline' ? ':root,\n[data-brand="northline"]' : `[data-brand="${brand.toLowerCase()}"]`;
  css.push(block(selector, lines));
}

// Semantic tokens per theme. Light is also the default on :root.
interface SemanticEntry {
  name: string;
  group: string;
  cssVar: string;
  tailwind: string[];
  description: string;
  modes: Record<Theme, { alias: string; alpha?: number }>;
}
const semantic = new Map<string, SemanticEntry>();
for (const theme of THEMES) {
  const tokens = (await tokensFor(source, 'Northline', theme)).filter((t) => collection(t) === 'Color collection');
  for (const token of tokens) {
    const name = token.path.at(-1) ?? '';
    const entry = semantic.get(name) ?? {
      name,
      group: token.path[1] ?? '',
      cssVar: `--${token.name}`,
      tailwind: tailwindKeys(name).map((k) => `nl:${k.utility}`),
      description: token.$description ?? '',
      modes: {} as SemanticEntry['modes'],
    };
    const match = REFERENCE.exec(String(token.original.$value));
    const alpha = alphaOf(token, theme);
    entry.modes[theme] = { alias: `--${names.get(match?.[1] ?? '') ?? ''}`, ...(alpha === undefined ? {} : { alpha }) };
    semantic.set(name, entry);
  }
  const selector = theme === 'Light' ? ':root,\n[data-theme="light"]' : '[data-theme="dark"]';
  css.push(block(selector, declarations(tokens, theme)));
}

// Primitive values, for the Token pipeline page.
const primitives = Object.fromEntries(
  reference
    .filter((t) => collection(t) === 'Primitives' && t.path[1] === 'Colors')
    .map((t) => [`--${t.name}`, String(t.original.$value)]),
);

// Tailwind theme (DESIGN.md §3.11). "inline reference" makes utilities use var(--nl-…) directly and emit no
// theme variables, so Tailwind's own prefixed variables can never overwrite a token with the same name.
const textStyles = [...new Set(reference.filter(isTextStyleToken).map((t) => t.path[1]))]
  .filter((style): style is string => Boolean(style))
  .map(textStyleName);
const space = reference.filter((t) => t.path[1] === 'Spacing').map((t) => t.name.replace(/^nl-space-/, ''));
const radius = reference.filter((t) => t.path[1] === 'Radius').map((t) => t.name.replace(/^nl-radius-/, ''));
const sizes = reference
  .filter((t) => t.path[1] === 'Sizes' && t.name !== 'nl-size-full') // Size-full (9999) is only for Radius-Full
  .map((t) => t.name.replace(/^nl-size-/, ''));

const theme: string[] = [
  HEADER,
  '/* Import after @import "tailwindcss" prefix(nl). Every class is nl:-prefixed (DESIGN.md §3.11, CLAUDE.md). */\n',
  '/* dark: is disabled: theme and brand come from data-theme and data-brand on <html>. */',
  '@custom-variant dark (&:not(*));\n',
  "/* Tailwind's defaults are removed, so only this system's tokens exist. */",
  block('@theme', [
    '--color-*: initial;',
    '--spacing: initial;',
    '--spacing-*: initial;',
    '--container-*: initial;',
    '--radius-*: initial;',
    '--shadow-*: initial;',
    '--inset-shadow-*: initial;',
    '--drop-shadow-*: initial;',
    '--text-shadow-*: initial;',
    '--text-*: initial;',
    '--font-*: initial;',
    '--font-weight-*: initial;',
    '--leading-*: initial;',
    '--tracking-*: initial;',
  ]),
  block('@theme inline reference', [
    '/* Semantic colours */',
    ...[...semantic.values()].flatMap((entry) =>
      tailwindKeys(entry.name).map(({ key }) => `${key}: var(${entry.cssVar});`),
    ),
    '/* Spacing (Space-*) */',
    ...space.map((s) => `--spacing-${s}: var(--nl-space-${s});`),
    '/* Sizes (Size-*), for width, height and size */',
    ...sizes.flatMap((s) =>
      ['width', 'min-width', 'max-width', 'height', 'min-height', 'max-height', 'size'].map(
        (k) => `--${k}-${s}: var(--nl-size-${s});`,
      ),
    ),
    '/* Radius (Radius-*) */',
    ...radius.map((r) => `--radius-${r}: var(--nl-radius-${r});`),
    '/* Shadows and layers (src/styles.css) */',
    ...SHADOWS.map((s) => `--shadow-${s}: var(--nl-shadow-${s});`),
    ...LAYERS.map((z) => `--z-index-${z}: var(--nl-z-${z});`),
  ]),
  '/* Text styles: one font shorthand each (DESIGN.md §3.4). Data styles use tabular figures. */',
  ...textStyles.map((style) =>
    block(`@utility text-${style}`, [
      `font: var(--nl-font-${style});`,
      ...(TABULAR_STYLES.has(style) ? ['font-variant-numeric: tabular-nums;'] : []),
    ]),
  ),
];

// JavaScript constants and their types.
const entries = [...semantic.values()];
const js = `${HEADER.replace('/*', '//').replace(' */', '')}
export const brands = ${JSON.stringify(BRANDS.map((b) => b.toLowerCase()))};
export const themes = ${JSON.stringify(THEMES.map((t) => t.toLowerCase()))};
export const semanticTokenNames = ${JSON.stringify(entries.map((e) => e.name))};
export const textStyleNames = ${JSON.stringify(textStyles)};
export const semanticTokens = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.name, e])), null, 2)};
export const aliasChains = ${JSON.stringify(brandChains, null, 2)};
export const primitiveColors = ${JSON.stringify(primitives, null, 2)};
export const tokenList = ${JSON.stringify(
  reference.map((t) => ({
    path: t.path.join('.'),
    collection: t.path[0],
    group: t.path.length > 2 ? t.path.at(-2) : '',
    name: t.path.at(-1),
    cssVar: `--${t.name}`,
    type: t.$type,
    description: t.$description ?? '',
  })),
  null,
  2,
)};
`;
const union = (values: readonly string[]) => values.map((v) => JSON.stringify(v)).join(' | ');
const dts = `${HEADER.replace('/*', '//').replace(' */', '')}
export type Brand = ${union(BRANDS.map((b) => b.toLowerCase()))};
export type Theme = ${union(THEMES.map((t) => t.toLowerCase()))};
export type SemanticTokenName = ${union(entries.map((e) => e.name))};
export type TextStyleName = ${union(textStyles)};
export interface SemanticToken {
  name: SemanticTokenName;
  group: 'Background' | 'Text' | 'Border' | 'Foreground' | 'Alpha';
  cssVar: \`--nl-\${string}\`;
  tailwind: string[];
  description: string;
  modes: Record<'Light' | 'Dark', { alias: \`--nl-color-\${string}\`; alpha?: number }>;
}
export declare const brands: readonly Brand[];
export declare const themes: readonly Theme[];
export declare const semanticTokenNames: readonly SemanticTokenName[];
export declare const textStyleNames: readonly TextStyleName[];
export declare const semanticTokens: Readonly<Record<SemanticTokenName, SemanticToken>>;
/** Alias CSS variable → the primitive (or Primary-*) variable it points at, per brand. */
export declare const aliasChains: Readonly<Record<string, Record<'Northline' | 'Garnet' | 'Voltic', string>>>;
/** Primitive colour CSS variable → hex. */
export declare const primitiveColors: Readonly<Record<string, string>>;
export interface TokenListItem {
  /** JSON path in tokens/design.tokens.json */
  path: string;
  collection: 'Primitives' | 'Alias Typography' | 'Alias Colors' | 'Color collection' | 'Alias Spacing & Radius';
  /** The group the token sits in (for example "Primary", "Spacing", "Font Size") */
  group: string;
  name: string;
  cssVar: \`--nl-\${string}\`;
  type: 'color' | 'dimension' | 'fontFamily' | 'fontWeight';
  description: string;
}
/** Every token in the JSON, in file order. */
export declare const tokenList: readonly TokenListItem[];
`;

await mkdir(DIST, { recursive: true });
await Promise.all([
  writeFile(`${DIST}tokens.css`, css.join('\n')),
  writeFile(`${DIST}tailwind-theme.css`, theme.join('\n')),
  writeFile(`${DIST}tokens.js`, js),
  writeFile(`${DIST}tokens.d.ts`, dts),
  copyFile(fileURLToPath(new URL('src/styles.css', import.meta.url)), `${DIST}styles.css`), // hand-written (S3)
]);
console.log(
  `Tokens built: ${reference.length} tokens, ${semantic.size} semantic, ${textStyles.length} text styles → packages/tokens/dist/`,
);
